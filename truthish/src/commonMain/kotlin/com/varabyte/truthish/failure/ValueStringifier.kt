/**
 * Extra information about how to render a value, beyond the value itself. Stringifiers that don't need a piece of it
 * ignore it.
 *
 * @property truncation How to shorten the value if it's long.
 */
class StringifierContext(val truncation: Truncation = Truncation.BothEnds) {
    companion object {
        val Default = StringifierContext()
    }

    // Written by hand rather than generated by a data class, so adding a field later can add an overload instead of
    // changing this signature, which would break callers compiled against an older version.
    fun copy(truncation: Truncation = this.truncation) = StringifierContext(truncation)
}

internal object Truncators {
    /**
     * The truncator reports use for collections, which shows at most 11 elements.
     */
    // NOTE: An odd number was intentionally chosen so that truncations that happen around an anchor can show the
    // same number of elements before and after.
    val forCollections = Truncator(maxElements = 11)

    /**
     * The truncator reports use for strings, which shows at most 100 characters.
     */
    val forStrings = Truncator(maxElements = 100)
}

/**
 * Converts a class into its most specific name available on this platform, e.g. to tell apart two classes that share a
 * simple name.
 */
internal expect fun KClass<*>.toQualifiedString(): String

/**
 * A base class for rendering a value in a report.
 *
 * NOTE: Subclasses are intentionally not public. Third-party libraries should treat the "object to text" logic as a
 * black box implementation detail. Users can file an issue if they find themselves needing to register additional
 * handlers.
 */
sealed class ValueStringifier(private val value: Any?) {
    companion object {
        /**
         * Creates the stringifier a report uses for [value], e.g. one that renders a list as `[ 1, 2, 3 ]`.
         */
        fun createFor(value: Any?, context: StringifierContext = StringifierContext.Default): ValueStringifier {
            val truncation = context.truncation
            return when (value) {
                is ValueStringifier -> value // In case caller already wrapped `value` in a stringifier themselves
                is Char -> CharStringifier(value)
                is CharSequence -> StringStringifier(value, truncation)
                is LineDiff -> LineDiffStringifier(value)
                is Map<*, *> -> MapStringifier(value, truncation)
                is Map.Entry<*, *> -> PairStringifier(value, truncation)
                is Pair<*, *> -> PairStringifier(value, truncation)
                is Triple<*, *, *> -> TripleStringifier(value, truncation)
                is Set<*> -> SetStringifier(value, truncation)
                is Iterable<*> -> IterableStringifier(value, truncation)
                is KClass<*> -> KClassStringifier(value)
                else -> AnyStringifier(value)
            }
        }
    }

    abstract fun render(): String

    final override fun toString() = render()

    /**
     * Extra detail to tell this value apart from another value that prints the same.
     */
    open fun toDetailString(): String = "Type: `${value?.let { it::class.simpleName }}`"
}

/**
 * A default Stringifier that can handle any case.
 */
internal class AnyStringifier(private val value: Any?) : ValueStringifier(value) {
    override fun render() = value?.let { "$it" } ?: "(null)"
}

private enum class Quote(val char: Char) {
    SINGLE('\''),
    DOUBLE('"'),
}

/**
 * Escapes this character the way it would be written inside a Kotlin literal delimited by [quote].
 *
 * This makes invisible characters like tabs, newlines and ANSI escape codes show up in reports, and lets a reported value
 * be pasted straight back into a test.
 */
private fun Char.toEscapedString(quote: Quote): String {
    return when {
        this == '\t' -> "\\t"
        this == '\n' -> "\\n"
        this == '\r' -> "\\r"
        this == '\b' -> "\\b"
        this == '\\' -> "\\\\"
        this == quote.char -> "\\$this"
        isISOControl() -> "\\u" + code.toString(16).uppercase().padStart(4, '0')
        else -> toString()
    }
}

/**
 * Shows this character in plain text without backslash escapes, so a backslash in the text is never mistaken for one.
 *
 * A tab is drawn as an arrow, as editors do, and other control characters as their symbols from Unicode's Control
 * Pictures block, e.g. `␛` for an escape. C1 control characters have no such symbol, so they're shown as their code.
 */
private fun Char.toVisibleString(): String {
    return when {
        this == '\t' -> "→"
        code < 0x20 -> Char(0x2400 + code).toString()
        code == 0x7F -> "␡"
        isISOControl() -> "<U+" + code.toString(16).uppercase().padStart(4, '0') + ">"
        else -> toString()
    }
}

internal class CharStringifier(private val value: Char) : ValueStringifier(value) {
    override fun render() = Quote.SINGLE.let { quote -> quote.char + value.toEscapedString(quote) + quote.char }
}

/**
 * Renders a string in quotes, e.g. `"abc"`.
 */
internal class StringStringifier(
    private val value: CharSequence,
    private val truncation: Truncation,
) : ValueStringifier(value) {
    // Characters are cut before they're escaped, so an escape like `\n` is never split
    override fun render() = Truncators.forStrings.truncate(value.toList(), truncation).joinToString(" ") { part ->
        when (part) {
            is TruncatedPart.Shown -> {
                val quote = Quote.DOUBLE
                part.values.joinToString("", prefix = quote.char.toString(), postfix = quote.char.toString()) {
                    it.toEscapedString(quote)
                }
            }
            is TruncatedPart.Hidden -> "… (${part.count} more ${if (part.count == 1) "char" else "chars"})"
        }
    }
}

/**
 * Renders a [LineDiff] as one line per diff line, each starting with `- ` (expected only), `+ ` (actual only) or two
 * spaces (both).
 *
 * Unchanged lines more than a few lines away from a change are collapsed, e.g. `… (40 unchanged lines)`. Invisible
 * characters are drawn as symbols, e.g. a tab as `→`.
 */
internal class LineDiffStringifier(private val diff: LineDiff) : ValueStringifier(diff) {
    private companion object {
        /** How many unchanged lines to show around each change. */
        const val CONTEXT_SIZE = 3
    }

    override fun render(): String {
        val lines = diff.lines
        val changedIndices = lines.indices.filter { lines[it] !is LineDiff.Line.Kept }
            // If every line matches, the strings differ in their final newline, so treat the end as the change
            .ifEmpty { listOf(lines.size) }
        val isShown = BooleanArray(lines.size) { index ->
            changedIndices.any { changedIndex -> abs(index - changedIndex) <= CONTEXT_SIZE }
        }

        return buildList {
            var index = 0
            while (index < lines.size) {
                val hiddenCount = (index until lines.size).takeWhile { !isShown[it] }.count()
                // Collapsing a single line would save nothing, since the marker takes a line too
                if (hiddenCount > 1) {
                    add("  … ($hiddenCount unchanged lines)")
                    index += hiddenCount
                    continue
                }

                val line = lines[index]
                val marker = when (line) {
                    is LineDiff.Line.Kept -> "  "
                    is LineDiff.Line.Removed -> "- "
                    is LineDiff.Line.Added -> "+ "
                }
                val text = line.text.toList().joinToString("") { it.toVisibleString() }
                // An empty line gets no trailing space after its marker
                add(if (text.isEmpty()) marker.trimEnd() else marker + text)
                index++
            }
        }.joinToString("\n")
    }
}

/**
 * Truncates [values] the way [truncation] asks for.
 */
private fun <T> Truncator.truncate(values: List<T>, truncation: Truncation): List<TruncatedPart<T>> =
    when (truncation) {
        Truncation.None -> listOf(TruncatedPart.Shown(values))
        Truncation.BothEnds -> truncate(values, Anchor.CenteredOn(0), Anchor.CenteredOn(values.lastIndex))
        is Truncation.Anchored -> truncate(values, truncation.firstAnchor, truncation.secondAnchor)
    }

/**
 * Joins these values, each formatted with its own stringifier, between [open] and [close], e.g. `[ 1, 2 ]` or `[]`.
 *
 * @param padded Whether to put spaces inside [open] and [close]. Collections use them, while fixed-size groups like
 *   triples read better tight, e.g. `(1, 2, 3)`.
 */
private fun Iterable<*>.joinValues(
    open: String,
    close: String,
    truncation: Truncation,
    padded: Boolean = true,
): String {
    val values = toList()
    if (values.isEmpty()) return "$open$close"

    val truncatedValues = Truncators.forCollections.truncate(values, truncation)
    val nestedContext = StringifierContext(truncation.inherited())
    val parts = truncatedValues.flatMap { part ->
        when (part) {
            is TruncatedPart.Shown -> part.values.map { ValueStringifier.createFor(it, nestedContext).render() }
            is TruncatedPart.Hidden -> listOf("… (${part.count} more)")
        }
    }

    val padding = if (padded) " " else ""
    return parts.joinToString(", ", prefix = "$open$padding", postfix = "$padding$close")
}

// Nested values don't share their parent's anchor (if an anchored truncation), since its index doesn't apply to them
private fun Truncation.inherited() = if (this == Truncation.None) Truncation.None else Truncation.BothEnds

internal class IterableStringifier(
    private val value: Iterable<*>,
    private val truncation: Truncation,
) : ValueStringifier(value) {
    override fun render() = value.joinValues("[", "]", truncation)
}

internal class MapStringifier(private val value: Map<*, *>, private val truncation: Truncation) :
    ValueStringifier(value) {
    override fun render() = value.entries.joinValues("{", "}", truncation)
}

// This should take precedence over IterableStringifier!
internal class SetStringifier(private val value: Set<*>, private val truncation: Truncation) :
    ValueStringifier(value) {
    override fun render() = value.joinValues("{", "}", truncation)
}

/**
 * Formats a pair (or map entry) the way it's usually written in Kotlin code, e.g. `"a" to 1`.
 */
internal class PairStringifier private constructor(
    value: Any,
    private val first: Any?,
    private val second: Any?,
    truncation: Truncation,
) : ValueStringifier(value) {
    constructor(pair: Pair<*, *>, truncation: Truncation) : this(pair, pair.first, pair.second, truncation)
    constructor(entry: Map.Entry<*, *>, truncation: Truncation) : this(entry, entry.key, entry.value, truncation)

    private val nestedContext = StringifierContext(truncation.inherited())

    override fun render() =
        "${createFor(first, nestedContext).wrapInParensIfNecessary()} to " +
            createFor(second, nestedContext).wrapInParensIfNecessary()

    // A nested value that is itself a pair needs parentheses to stay unambiguous, e.g. `(1 to 2) to 3`
    private fun ValueStringifier.wrapInParensIfNecessary(): String {
        val rendered = render()
        return if (this is PairStringifier) "($rendered)" else rendered
    }
}

internal class TripleStringifier(private val value: Triple<*, *, *>, private val truncation: Truncation) :
    ValueStringifier(value) {
    override fun render() = value.toList().joinValues("(", ")", truncation, padded = false)
}

internal class KClassStringifier(private val value: KClass<*>) : ValueStringifier(value) {
    // Anonymous classes have no simple name
    override fun render() = value.simpleName ?: value.toQualifiedString()
    override fun toDetailString() = value.toQualifiedString()
}
